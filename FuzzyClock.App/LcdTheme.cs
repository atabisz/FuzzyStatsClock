namespace FuzzyClock.App;

public enum LcdTheme { Green, Amber, Blue, Teal, Red, Vfd, Nixie, Magenta, Purple, Cyan, Lime, Cream, Ice, Mint, Lavender, LcdGrey, Paper }

public static class LcdPalette
{
    public static (System.Windows.Media.Color Lit, System.Windows.Media.Color Ghost, System.Windows.Media.Color Background)
        Get(LcdTheme theme) => theme switch
    {
        LcdTheme.Green    => (Color(0x00,0xFF,0x41), Color(0x00,0x33,0x10), Color(0x00,0x1A,0x00)),
        LcdTheme.Amber    => (Color(0xFF,0xAA,0x00), Color(0x3D,0x28,0x00), Color(0x1A,0x0A,0x00)),
        LcdTheme.Blue     => (Color(0x00,0xCF,0xFF), Color(0x00,0x2A,0x35), Color(0x00,0x00,0x1A)),
        LcdTheme.Teal     => (Color(0x00,0xB4,0xB4), Color(0x00,0x25,0x25), Color(0x00,0x10,0x10)),
        LcdTheme.Red      => (Color(0xFF,0x22,0x00), Color(0x38,0x08,0x00), Color(0x1A,0x00,0x00)),
        LcdTheme.Vfd      => (Color(0x14,0xF0,0xA0), Color(0x02,0x3A,0x28), Color(0x00,0x1A,0x10)),
        LcdTheme.Nixie    => (Color(0xFF,0x60,0x00), Color(0x3D,0x18,0x00), Color(0x1A,0x08,0x00)),
        LcdTheme.Magenta  => (Color(0xFF,0x00,0xCC), Color(0x3D,0x00,0x30), Color(0x1A,0x00,0x15)),
        LcdTheme.Purple   => (Color(0xCC,0x00,0xFF), Color(0x30,0x00,0x40), Color(0x15,0x00,0x1A)),
        LcdTheme.Cyan     => (Color(0x00,0xFF,0xFF), Color(0x00,0x38,0x38), Color(0x00,0x1A,0x1A)),
        LcdTheme.Lime     => (Color(0xCC,0xFF,0x00), Color(0x2E,0x38,0x00), Color(0x14,0x1A,0x00)),
        LcdTheme.Cream    => (Color(0xFF,0xEE,0xDD), Color(0x3D,0x30,0x20), Color(0x1A,0x12,0x08)),
        LcdTheme.Ice      => (Color(0xB0,0xD8,0xFF), Color(0x1A,0x2D,0x3D), Color(0x0A,0x15,0x20)),
        LcdTheme.Mint     => (Color(0x66,0xFF,0xCC), Color(0x00,0x3D,0x28), Color(0x00,0x1A,0x12)),
        LcdTheme.Lavender => (Color(0xCC,0x99,0xFF), Color(0x28,0x00,0x40), Color(0x12,0x00,0x18)),
        LcdTheme.LcdGrey  => (Color(0x2A,0x30,0x20), Color(0x8A,0x90,0x80), Color(0xC8,0xD0,0xC0)),
        LcdTheme.Paper    => (Color(0x1A,0x1A,0x18), Color(0x90,0x90,0xA0), Color(0xF0,0xF0,0xE8)),
        _ => throw new System.ArgumentOutOfRangeException(nameof(theme))
    };
    private static System.Windows.Media.Color Color(byte r, byte g, byte b)
        => System.Windows.Media.Color.FromRgb(r, g, b);
}
